"""Lean 4 source parser for the RAG index: declarations with full name, kind, complete (multi-line) signature,
docstring, attributes, variables in scope and module. Extends madalean/names.py's light parser (namespaces,
sections, `_root_`) with `/-- … -/` docstrings, attributes, `alias ⟨a, b⟩`, `instance (priority := …)`, and the
names generated by `@[to_additive]` (from Mathlib's `#align` lines when present — Lean 4.9 era — else guessed with
to_additive's dictionary)."""
from __future__ import annotations

import re
from dataclasses import dataclass, field

PARSER_VERSION = 6

_MODS = r"(?:(?:private|protected|noncomputable|nonrec|partial|unsafe|scoped|local)\s+)*"
_KW = r"(theorem|lemma|def|abbrev|instance|structure|class\s+inductive|class|inductive|alias|opaque|axiom|irreducible_def)"
_DECL = re.compile(rf"^(?P<attrs>(?:@\[.*?\]\s*)*){_MODS}{_KW}\b\s*(?P<rest>.*)$")
_NS = re.compile(r"^namespace\s+(\S+)")
_END = re.compile(r"^end(?:\s+(\S+))?\s*$")
_SECTION = re.compile(r"^(?:noncomputable\s+)?section(?:\s+(\S+))?\s*$")
_VARIABLE = re.compile(r"^variable\s+(.*)$")
_ALIGN = re.compile(r"^#align\s+\S+\s+(\S+)")
_PRIVATE = re.compile(r"^(?:@\[.*?\]\s*)*(?:\w+\s+)*private\s")
_OPEN = {"(": ")", "[": "]", "{": "}", "⦃": "⦄", "⟨": "⟩"}
_CLOSE = {v: k for k, v in _OPEN.items()}


@dataclass
class Decl:
    name: str
    kind: str
    signature: str
    doc: str = ""
    attrs: str = ""
    module: str = ""
    context: str = ""            # `variable`s in scope (the signature may rely on them)
    origin: str = ""             # for generated names: the declaration they come from
    line: int = 0
    deprecated: bool = False
    extra: dict = field(default_factory=dict)


# ------------------------------------------------------------------ to_additive dictionary (subset of Mathlib's)
_ADD_WORDS = [("finprod", "finsum"), ("prod", "sum"), ("products", "sums"), ("product", "sum"),
              ("mul", "add"), ("smul", "vadd"), ("one", "zero"), ("inv", "neg"), ("div", "sub"),
              ("npow", "nsmul"), ("zpow", "zsmul"), ("pow", "nsmul"), ("monoid", "addMonoid"),
              ("submonoid", "addSubmonoid"), ("group", "addGroup"), ("subgroup", "addSubgroup"),
              ("semigroup", "addSemigroup"), ("magma", "addMagma"), ("units", "addUnits"), ("unit", "addUnit"),
              ("isUnit", "isAddUnit"), ("isSquare", "even"), ("square", "even"), ("commute", "addCommute"),
              ("semiconj", "addSemiconj"), ("orderOf", "addOrderOf"), ("mulIndicator", "indicator"),
              ("mulSupport", "support"), ("torsion", "addTorsion"), ("exponent", "addExponent")]
_ADD = {a.lower(): b for a, b in _ADD_WORDS}
_SYM_WORDS = {"IsSquare": "Even", "CommMonoid": "AddCommMonoid", "CommGroup": "AddCommGroup",
              "CommSemigroup": "AddCommSemigroup", "Monoid": "AddMonoid", "Group": "AddGroup",
              "Semigroup": "AddSemigroup", "Mul": "Add", "One": "Zero", "MulOneClass": "AddZeroClass",
              "DivisionMonoid": "SubtractionMonoid", "DivisionCommMonoid": "SubtractionCommMonoid",
              "CommSemiring": "CommSemiring", "MonoidHom": "AddMonoidHom", "Units": "AddUnits",
              "IsUnit": "IsAddUnit", "Submonoid": "AddSubmonoid", "Subgroup": "AddSubgroup"}
_SYM_RE = re.compile(r"(?<![\w.])(" + "|".join(sorted(_SYM_WORDS, key=len, reverse=True)) + r")(?![\w'])")


def _camel_parts(s: str) -> list[str]:
    return re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z0-9']+|[^A-Za-z0-9']+", s)


def additive_name(name: str) -> str:
    def comp(c: str) -> str:
        out = []
        for piece in re.split(r"(_)", c):
            if piece == "_" or not piece:
                out.append(piece)
                continue
            primes = len(piece) - len(piece.rstrip("'"))
            if primes and piece.rstrip("'"):
                out.append(comp(piece.rstrip("'")) + "'" * primes)
                continue
            low = piece[:1].lower() + piece[1:]
            if low.lower() in _ADD:
                rep = _ADD[low.lower()]
                out.append(rep[:1].upper() + rep[1:] if piece[:1].isupper() else rep)
                continue
            parts = _camel_parts(piece)
            res = []
            for p in parts:
                r = _ADD.get(p.lower())
                res.append((r[:1].upper() + r[1:] if p[:1].isupper() else r) if r else p)
            out.append("".join(res))
        return "".join(out)
    return ".".join(comp(c) for c in name.split("."))


def additive_signature(sig: str) -> str:
    """Rough additive version of a multiplicative statement (search text and hints only, never trusted)."""
    sig = _SYM_RE.sub(lambda m: _SYM_WORDS[m.group(1)], sig)
    sig = sig.replace("∏", "∑").replace(" * ", " + ").replace(" / ", " - ")
    sig = re.sub(r"([\w']+)⁻¹", r"-\1", sig)
    sig = re.sub(r"([\w']+) \^ ([\w']+)", r"\2 • \1", sig)
    sig = re.sub(r"\(1 :", "(0 :", sig)
    sig = re.sub(r"(?<![\w.])1(?= [<≤=])|(?<=[<≤=] )1(?![\w.])", "0", sig)
    sig = re.sub(r"^alias of (\S+)", lambda m: "alias of " + additive_name(m.group(1)), sig)
    return sig


def _to_additive(attrs: str) -> tuple[bool, str, str]:
    """(present, explicit name, docstring) of a `@[to_additive …]` attribute."""
    m = re.search(r"to_additive\b(.*)", attrs, re.S)
    if not m:
        return False, "", ""
    rest = m.group(1)
    depth, j, in_str = 0, 0, False           # cut at the end of this attribute item
    for j, ch in enumerate(rest):
        if ch == '"' and (j == 0 or rest[j - 1] != "\\"):
            in_str = not in_str
            continue
        if in_str:
            continue
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            if depth == 0:
                break
            depth -= 1
        elif ch == "," and depth == 0:
            break
    else:
        j = len(rest)
    rest = rest[:j]
    rest = re.sub(r"\((?:[^()]|\([^()]*\))*\)", " ", rest)          # (attr := simp) (reorder := …)
    doc = ""
    md = re.search(r'"((?:[^"\\]|\\.)*)"', rest, re.S)
    if md:
        doc = md.group(1)
        rest = rest[: md.start()] + rest[md.end():]
    mn = re.match(r"\s*(?:existing\s+)?([^\s\"]+)", rest)
    name = mn.group(1) if mn and not mn.group(1).startswith("(") else ""
    return True, name, doc


def _sig_end(text: str) -> int:
    """Index where the signature ends (`:=` at bracket depth 0, ` where`, or a `|` pattern line)."""
    depth = 0
    i = 0
    n = len(text)
    while i < n:
        ch = text[i]
        if ch in _OPEN:
            depth += 1
        elif ch in _CLOSE:
            depth = max(0, depth - 1)
        elif depth == 0:
            if text.startswith(":=", i):
                return i
            if text.startswith("where", i) and (i == 0 or text[i - 1].isspace()) and \
                    (i + 5 == n or not (text[i + 5].isalnum() or text[i + 5] == "_")):
                return i
            if ch == "|" and "\n" in text[:i] and text[text.rfind("\n", 0, i) + 1:i].strip() == "":
                return i
        i += 1
    return -1


def parse_source(text: str, module: str = "") -> list[Decl]:
    out: list[Decl] = []
    lines = text.split("\n")
    stack: list[tuple[str, str, list[str]]] = []       # (ns|sec, name, variables declared in this scope)
    top_vars: list[str] = []
    pending_doc, pending_attrs = "", ""
    last: Decl | None = None
    last_gen: list[str] = []
    i, n = 0, len(lines)
    while i < n:
        raw = lines[i]
        line = raw.strip()
        if line.startswith("/-"):
            is_doc = line.startswith("/--")
            buf = [line]
            depth = line.count("/-") - line.count("-/")
            while depth > 0 and i + 1 < n:
                i += 1
                buf.append(lines[i])
                depth += lines[i].count("/-") - lines[i].count("-/")
            if is_doc:
                d = "\n".join(buf)
                d = d[3:]
                d = d[: d.rfind("-/")] if "-/" in d else d
                pending_doc = re.sub(r"[ \t]+\n", "\n", d).strip()
            i += 1
            continue
        if not line or line.startswith("--"):
            i += 1
            continue
        ma = _ALIGN.match(line)
        if ma:
            target = ma.group(1)
            if last is not None and target != last.name and target not in last_gen and last.extra.get("to_additive"):
                last_gen.append(target)
                out.append(Decl(target, last.kind, additive_signature(last.signature),
                                last.extra.get("add_doc") or "", "", last.module, additive_signature(last.context),
                                origin=last.name, line=last.line))
                last.extra["to_additive"] = False
            i += 1
            continue
        if line.startswith("#"):
            i += 1
            continue
        if line.startswith("attribute [") and "to_additive" in line:
            attr_txt = line
            while attr_txt.count("[") > attr_txt.count("]") or attr_txt.count('"') % 2 == 1:
                if i + 1 >= n:
                    break
                i += 1
                attr_txt += "\n" + lines[i].strip()
            tail = attr_txt[attr_txt.rfind("]") + 1:].strip()
            if not tail and i + 1 < n:
                i += 1
                tail = lines[i].strip()
            ta, tname, tdoc = _to_additive(attr_txt[attr_txt.find("[") + 1: attr_txt.rfind("]")])
            ns = ".".join(nm for k, nm, _ in stack if k == "ns")
            src = tail.split()[0] if tail else ""
            if ta and tname and src:
                full = tname if not ns or "." in tname else f"{ns}.{tname}"
                src_full = src if not ns or src.startswith(ns + ".") else f"{ns}.{src}"
                d = Decl(full, "theorem", "", tdoc, "", module, "", origin=src_full, line=i)
                d.extra["origin_candidates"] = [src_full, src]
                out.append(d)
            i += 1
            continue
        if line.startswith("@[") and not _DECL.match(line):
            attrs = line
            while attrs.count("[") > attrs.count("]") and i + 1 < n:
                i += 1
                attrs += " " + lines[i].strip()
            rest_line = attrs[_attr_end(attrs):].strip()
            pending_attrs += " " + attrs[:_attr_end(attrs)]
            if not rest_line:
                i += 1
                continue
            line = rest_line
        m = _NS.match(line)
        if m:
            stack.append(("ns", m.group(1), []))
            pending_doc = pending_attrs = ""
            i += 1
            continue
        m = _SECTION.match(line)
        if m:
            stack.append(("sec", m.group(1) or "", []))
            i += 1
            continue
        m = _END.match(line)
        if m:
            if stack:
                stack.pop()
            i += 1
            continue
        m = _VARIABLE.match(line)
        if m:
            v = m.group(1)
            while i + 1 < n and lines[i + 1].startswith((" ", "\t")) and lines[i + 1].strip() and \
                    not _DECL.match(lines[i + 1].strip()):
                i += 1
                v += " " + lines[i].strip()
            (stack[-1][2] if stack else top_vars).append(v.strip())
            i += 1
            continue
        full_line = (pending_attrs.strip() + " " + line).strip() if pending_attrs else line
        m = _DECL.match(full_line)
        if not m:
            pending_doc, pending_attrs = "", ""
            i += 1
            continue
        attrs = (m.group("attrs") or "").strip()
        kind = re.sub(r"\s+", " ", m.group(2))
        rest = m.group("rest")
        private = bool(_PRIVATE.match(full_line))
        # gather the signature (up to 40 lines)
        text = rest
        j = i
        while _sig_end(text) < 0 and j + 1 < n and j - i < 40:
            nxt = lines[j + 1]
            st = nxt.strip()
            if st and not nxt.startswith((" ", "\t")) and (_DECL.match(st) or st.startswith(("@[", "/-", "#", "end", "namespace", "section"))):
                break
            j += 1
            text += "\n" + nxt
        doc, pending_doc, pending_attrs = pending_doc, "", ""
        ns = ".".join(nm for k, nm, _ in stack if k == "ns")
        context = "; ".join(top_vars + [v for _, _, vs in stack for v in vs])[-600:]
        cut = _sig_end(text)
        head = text if cut < 0 else text[:cut]
        names: list[tuple[str, str]] = []
        if kind == "alias":
            mm = re.match(r"\s*⟨\s*([^,⟩]+?)\s*,\s*([^⟩]+?)\s*⟩\s*:=\s*(\S+)", text)
            if mm:
                for nm, part in ((mm.group(1), "mp"), (mm.group(2), "mpr")):
                    if nm != "_":
                        names.append((nm, f"alias of {mm.group(3)} ({part})"))
            else:
                mm = re.match(r"\s*(\S+)\s*:=\s*(\S+)", text)
                if mm:
                    names.append((mm.group(1), f"alias of {mm.group(2)}"))
        else:
            h = head.lstrip()
            if kind == "instance":
                h = re.sub(r"^\(priority\s*:=\s*[^)]*\)\s*", "", h)
            mm = re.match(r"([^\s:({\[⦃⟨]+)(.*)$", h, re.S)
            if mm and not h.startswith((":", "(", "[", "{", "⦃", "⟨")):
                sig = re.sub(r"[ \t]*\n[ \t]*", " ", mm.group(2)).strip()
                names.append((mm.group(1), sig))
        i = j + 1
        if private or not names:
            last = None
            continue
        last_gen = []
        for nm, sig in names:
            full = nm[len("_root_."):] if nm.startswith("_root_.") else (f"{ns}.{nm}" if ns else nm)
            d = Decl(full, kind, sig[:2000], doc[:3000], attrs[:400], module, context,
                     deprecated="deprecated" in attrs, line=i)
            ta, tname, tdoc = _to_additive(attrs)
            if ta:
                d.extra["to_additive"] = True
                d.extra["add_doc"] = tdoc
                if tname:
                    if "." in tname or not ns:
                        add_full = tname if not ns or tname.startswith(ns + ".") or "." in tname else f"{ns}.{tname}"
                    else:
                        prefix = full.rsplit(".", 1)[0] if "." in full else ""
                        add_full = f"{prefix}.{tname}" if prefix else tname
                    out.append(Decl(add_full, kind, additive_signature(d.signature), tdoc, "", module,
                                    additive_signature(context), origin=full, line=i))
                    last_gen.append(add_full)
                    d.extra["to_additive"] = False
                    d.extra["guess"] = ""
                else:
                    d.extra["guess"] = additive_name(full)
            out.append(d)
            last = d
    # names left to guess (no #align and no explicit name)
    have = {d.name for d in out}
    for d in list(out):
        g = d.extra.get("guess")
        if d.extra.get("to_additive") and g and g != d.name and g not in have:
            out.append(Decl(g, d.kind, additive_signature(d.signature), d.extra.get("add_doc") or "", "", d.module,
                            additive_signature(d.context), origin=d.name, line=d.line, extra={"guessed": True}))
            have.add(g)
    return out


def _attr_end(s: str) -> int:
    """Index just after the last attribute group `@[…]` at the start of s."""
    i = 0
    while True:
        while i < len(s) and s[i].isspace():
            i += 1
        if not s.startswith("@[", i):
            return i
        depth = 0
        k = i + 1
        while k < len(s):
            if s[k] == "[":
                depth += 1
            elif s[k] == "]":
                depth -= 1
                if depth == 0:
                    break
            k += 1
        i = k + 1
