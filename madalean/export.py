        r"\titlespacing*{\section}{0pt}{14pt}{6pt}",
        r"\setlist{itemsep=1pt,parsep=0pt,topsep=3pt}",
        r"\newcommand\MLbs{\char`\\}\newcommand\MLlb{\char`\{}\newcommand\MLrb{\char`\}}",
        r"\fvset{breaklines=true,breakanywhere=true,fontsize=\small,frame=single,framesep=2.5mm,"
