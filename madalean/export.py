def build_html(c: Content) -> str:
    t = T[c.lang]
    katex = _katex()
    md = (lambda s: texio.markdown_to_html(cite_text(s, c), keep_tex=bool(katex)))

    def lean(code: str) -> str:
        return '<pre class="lean">' + "".join(f"<span>{html.escape(line) or ' '}</span>"
                                              for line in code.strip("\n").split("\n")) + "</pre>"
    badge = f'<span class="badge {"ok" if c.proved else "warn"}">{t["verified"] if c.proved else t["not_proved"]}</span>'
    out = [f'<!doctype html><html lang="{c.lang}"><head><meta charset="utf-8">'
           f'<meta name="viewport" content="width=device-width,initial-scale=1"><title>{html.escape(c.title)}</title>'
           f"<style>{_HTML_CSS}</style>{katex}</head><body>",
           f"<h1>{html.escape(c.title)}</h1><p><code>{html.escape(c.theorem)}</code> — {badge}</p>"]
    if c.nl_statement:
        out.append(f'<h2>{t["statement"]}</h2><div class="box">{md(c.nl_statement)}</div>')
    out.append(f'<h2>{t["lean_statement"]}</h2>' + (lean(c.lean_statement) if c.lean_statement.strip()
                                                     else f"<p>{t['no_statement']}</p>"))
    if c.notes.strip():
        out.append(f'<h3>{t["gloss"]}</h3><p class="note">{t["ai_gloss"]}</p>{md(c.notes)}')
    if not c.proved:
        out.append(f'<div class="warnbox">{html.escape(t["not_proved_text"])}</div>')
        if c.conditional:
            out.append(f'<div class="warnbox">{html.escape(c.conditional)}</div>')
    else:
        if c.informal.strip():
            out.append(f'<h2>{t["informal"]}</h2><p class="note">{t["ai_note"]}</p>{md(c.informal)}')
        rows = "".join(f"<tr><td><strong>{html.escape(k)}</strong></td><td><code>{html.escape(v)}</code></td></tr>"
                       for k, v in _stamp_rows(c))
        out.append(f'<h2>{t["lean_proof"]}</h2>{lean(c.proof)}<div class="stamp"><strong>{t["stamp"]} — '
                   f'{t["verified"]} ✓</strong><table>{rows}</table><p class="note">{html.escape(t["strict"])}</p></div>')
        if c.explanation.strip():
            out.append(f'<h2>{t["appendix"]}</h2><p class="note">{t["ai_note"]}</p>{md(c.explanation)}')
    if c.bib:
        from .research import biblio
        labels = biblio.labels_for(c.bib)
        out.append(f'<h2>{t["references"]}</h2><ol class="refs">' + "".join(
            f'<li id="ref-{html.escape(k)}">[{html.escape(labels[k])}] {biblio.reference_html(it)}</li>'
            for k, it in c.bib) + "</ol>")
    out.append(f"<footer>{html.escape(t['generated'].format(date=_fmt_date(c.date, c.lang)))}</footer></body></html>")
    return "\n".join(out)


# ---------------------------------------------------------------- compilation
def tectonic_cmd() -> list[str] | None:
    """The prefix's tectonic with the pinned bundle, cache only (offline), untrusted input (no shell escape)
    — ARCHITECTURE §18. None when the prefix has no tectonic or its bundle was not installed."""
    tec = deps.tool("tectonic")
    if not tec or deps.tool_info("tectonic")["source"] != "prefix" or not deps.tex_files_dir().is_dir():
        return None
    try:
        from .deps import manifest
        url = manifest.component("tex-bundle")["url"]
    except (OSError, KeyError, ValueError):
        return None
    return [tec, "-X", "compile", "--untrusted", "--only-cached", "--keep-logs", "--bundle", url]


def _engines() -> list[list[str]]:
    """Commands to try, best first. Each is run in the document's directory with the file name appended.
    tectonic from the prefix first; a system XeLaTeX/LuaLaTeX only as a fallback (§18). S-AL (D44): the user's
    `tex_engine` reorders them (system = the TeX Live first, tectonic as fallback; tectonic = tectonic only when
    present). Every engine runs confined the same way (tex_confine)."""
    out = []
    pref = deps.preference("tex_engine")
    tec = tectonic_cmd()
    if tec:
        out.append(tec)
    if pref == "tectonic" and tec:
        return out
    latexmk = deps.tool("latexmk")
    for eng in ("xelatex", "lualatex"):
        if not deps.tool(eng):
            continue
        if eng == "lualatex" and not texio.tex_font_file("luaotfload-main.lua"):
            continue                       # LuaLaTeX without luaotfload cannot load any OpenType font (fontspec)
        if latexmk:
            out.append([latexmk, f"-{eng}", "-norc", "-interaction=nonstopmode", "-halt-on-error", "-file-line-error",
                        "-latexoption=-no-shell-escape", "-silent"])
        else:
            out.append([deps.tool(eng), "-interaction=nonstopmode", "-halt-on-error", "-no-shell-escape",
                        "\x00twice"])
    if pref == "system" and tec and len(out) > 1:
        out = out[1:] + out[:1]
    return out


TEX_ENV_ALLOW = ("PATH", "LANG", "LANGUAGE", "TZ", "HOME", "TEXMFHOME", "TEXMFVAR", "TEXMFCONFIG", "TEXINPUTS",
                 "SOURCE_DATE_EPOCH", "FONTCONFIG_FILE", "FONTCONFIG_PATH", "TECTONIC_CACHE_DIR")


def tex_env() -> dict:
    """Our generated TeX only: no shell escape, TeX may only read/write files below the working directory
    (kpathsea engines; tectonic ignores openin_any/openout_any — S-H: the sandbox of `_run` is the boundary).
    No API key or token in the environment."""
    env = {k: v for k, v in os.environ.items() if k in TEX_ENV_ALLOW or k.startswith("LC_")}
    env.update({"openin_any": "p", "openout_any": "p", "shell_escape": "f"})
    if deps.installed():
        env.setdefault("TECTONIC_CACHE_DIR", str(deps.tectonic_cache()))
        if deps.fontconfig_file().exists():
            env.setdefault("FONTCONFIG_FILE", str(deps.fontconfig_file()))
    return env


def tex_confine(cmd: list[str], cwd: Path, env: dict) -> list[str]:
    """S-H finding F5: model/paper/BibTeX text reaches TeX; `^^5c` (TeX's hex notation for a backslash) rebuilt
    `\\input`/`\\openout` past the sanitiser, and tectonic --untrusted read /etc/… and wrote files at absolute
    paths. Every TeX run is therefore confined: the build directory writable, the prefix (tectonic bundle, fonts)
    and the TeX/font system trees read-only, the rest of the home directory absent, no network."""
    from . import leansandbox
    # S-AC: a private writable home in both modes (font caches, TEXMFVAR, luaotfload's names…), never the user's
    env.update(leansandbox.home_env(leansandbox.private_home("tex")))
    j = os.path.join
    env.update({"TEXMFVAR": j(env["HOME"], ".texlive", "texmf-var"),
                "TEXMFCONFIG": j(env["HOME"], ".texlive", "texmf-config")})
    if not leansandbox.bwrap():
        return cmd
    home = Path.home()
    ro = [deps.home(), home / ".local" / "share" / "fonts", home / ".fonts", Path("/var/lib/texmf"),
          Path("/var/cache/fontconfig"), Path(cmd[0]).resolve().parent.parent]
    for k in ("FONTCONFIG_FILE", "TEXMFHOME"):
        if env.get(k):
            ro.append(Path(env[k]).parent if k == "FONTCONFIG_FILE" else Path(env[k]))
    rw = [cwd]
    if env.get("TECTONIC_CACHE_DIR"):
        rw.append(Path(env["TECTONIC_CACHE_DIR"]))     # formats may be (re)generated; TeX-only content
    return leansandbox.confine(cmd, ro, rw, cwd)


async def _run(cmd: list[str], cwd: Path, timeout: float) -> tuple[int | None, str]:
    """Run a TeX command; returns (returncode or None on timeout, output tail). Kills the whole group on timeout."""
    env = tex_env()
    cmd = tex_confine(cmd, cwd, env)
    try:
        proc = await asyncio.create_subprocess_exec(*cmd, cwd=str(cwd), stdout=asyncio.subprocess.PIPE,
                                                    stderr=asyncio.subprocess.STDOUT, stdin=asyncio.subprocess.DEVNULL,
                                                    start_new_session=True, env=env)
    except OSError as e:
        return 127, str(e)

    def kill():
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except (ProcessLookupError, PermissionError):
            pass
    try:
        out, _e = await asyncio.wait_for(proc.communicate(), timeout)
    except asyncio.TimeoutError:
        kill()
        await proc.wait()
        return None, "timeout"
    except asyncio.CancelledError:
        kill()
        raise
    return proc.returncode, out.decode("utf-8", "replace")[-4000:]


async def compile_pdf(tex: str, tmp_root: Path, timeout: float = 120.0,
                      engines: list[list[str]] | None = None,
                      extra_files: dict[str, str | bytes] | None = None) -> tuple[bytes | None, str, bool]:
    """(pdf bytes or None, log tail, timed_out). Tries each engine in turn on the same source. `extra_files`
    (name → content, plain names only: refs.bib…) are written next to the document."""
    tmp_root.mkdir(parents=True, exist_ok=True)
    logs: list[str] = []
    for cmd in (engines if engines is not None else _engines()):
        work = Path(await asyncio.to_thread(tempfile.mkdtemp, prefix="export-", dir=tmp_root))
        try:
            await asyncio.to_thread((work / "doc.tex").write_text, tex, "utf-8")
            for name, content in (extra_files or {}).items():
                if not re.fullmatch(r"[A-Za-z0-9_.-]{1,80}", name) or name.startswith("."):
                    continue
                target = work / name
                if isinstance(content, bytes):
                    await asyncio.to_thread(target.write_bytes, content)
                else:
                    await asyncio.to_thread(target.write_text, content, "utf-8")
            twice = cmd[-1] == "\x00twice"
            base = cmd[:-1] if twice else cmd
            rc, out = await _run(base + ["doc.tex"], work, timeout)
            if twice and rc == 0:
                if "refs.bib" in (extra_files or {}):            # no latexmk: run the bibliography tool by hand
                    tool = "biber" if "\\addbibresource" in tex else "bibtex"
                    if deps.tool(tool):
                        await _run([deps.tool(tool), "doc"], work, timeout)
                    rc, out = await _run(base + ["doc.tex"], work, timeout)
                rc, out = await _run(base + ["doc.tex"], work, timeout)
            if rc is None:
                return None, f"{Path(cmd[0]).name}: timeout after {timeout:.0f} s", True
            pdf = work / "doc.pdf"
            if rc == 0 and pdf.exists():
                return await asyncio.to_thread(pdf.read_bytes), "", False
            logf = work / "doc.log"
            tail = (await asyncio.to_thread(logf.read_text, "utf-8", "replace"))[-3000:] if logf.exists() else out
            logs.append(f"[{' '.join(Path(x).name for x in base[:2])}] {tail}")
        finally:
            await asyncio.to_thread(shutil.rmtree, work, True)
    return None, "\n".join(logs)[-6000:], False


async def make_pdf(c: Content, tmp_root: Path, timeout: float = 120.0) -> Export:
    """PDF, else PDF with the model texts verbatim, else HTML. Never raises for content problems. With a
    bibliography: biblatex+biber, else bibtex+amsalpha, else (or when those fail) a hand-formatted thebibliography."""
    name = slugify(c.title)
    f = await asyncio.to_thread(texio.fonts)
    engines = _engines()
    log = ""
    backends = [c.bib_backend or bib_backend()] if c.bib else [""]
    if c.bib and backends[0] != "manual":
        backends.append("manual")
    if engines:
        done = False
        for backend in backends:
            c.bib_backend = backend
            extra = {"refs.bib": bib_file(c)} if c.bib else None
            for verbatim in (False, True):
                tex = await asyncio.to_thread(build_tex, c, verbatim, f)
                pdf, log, timed_out = await compile_pdf(tex, tmp_root, timeout, engines, extra)
                if pdf:
                    return Export(f"{name}.pdf", CONTENT_TYPES["pdf"], pdf, "verbatim" if verbatim else "", log)
                if timed_out:
                    done = True
                    break
            if done:
                break
    else:
        log = "no TeX engine (xelatex/lualatex) found"
    page = await asyncio.to_thread(build_html, c)
    return Export(f"{name}.html", CONTENT_TYPES["html"], page.encode("utf-8"), "html", log)


async def export_dossier(d: Dossier, fmt: str, *, lang: str = "fr", ws_info: dict | None = None, tmp_root: Path,
                         timeout: float = 120.0, bib_keys: list[str] | None = None,
                         bib_path: Path | None = None, bib_entries: list | None = None) -> Export:
    if fmt not in FORMATS:
        raise ValueError(f"unknown format {fmt!r}")
    c = collect(d, lang, ws_info, bib_keys, bib_path, bib_entries)
    name = slugify(c.title)
    if fmt == "pdf":
        return await make_pdf(c, Path(tmp_root), timeout)
    if fmt == "tex":
        f = await asyncio.to_thread(texio.fonts)
        if c.bib:
            c.bib_backend = "manual"          # a single self-contained .tex file (the zip carries refs.bib)
        tex = await asyncio.to_thread(build_tex, c, False, f)
        return Export(f"{name}.tex", CONTENT_TYPES["tex"], tex.encode("utf-8"))
    if fmt == "lean":
        return Export(f"{name}.lean", CONTENT_TYPES["lean"], build_lean(c).encode("utf-8"))
    if fmt == "md":
        return Export(f"{name}.md", CONTENT_TYPES["md"], build_md(c).encode("utf-8"))
    if fmt == "html":
        return Export(f"{name}.html", CONTENT_TYPES["html"], (await asyncio.to_thread(build_html, c)).encode("utf-8"))
    # zip: pdf (or its HTML fallback) + tex + lean + md
    pdf = await make_pdf(c, Path(tmp_root), timeout)
    f = await asyncio.to_thread(texio.fonts)
    tex = await asyncio.to_thread(build_tex, c, pdf.fallback == "verbatim", f)

    def pack() -> bytes:
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
            z.writestr(f"{name}/{pdf.filename}", pdf.data)
            z.writestr(f"{name}/{name}.tex", tex)
            z.writestr(f"{name}/{name}.lean", build_lean(c))
            z.writestr(f"{name}/{name}.md", build_md(c))
            if c.bib:
                z.writestr(f"{name}/refs.bib", bib_file(c))
        return buf.getvalue()
    return Export(f"{name}.zip", CONTENT_TYPES["zip"], await asyncio.to_thread(pack), pdf.fallback, pdf.log)
