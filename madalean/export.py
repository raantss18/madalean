_LABEL = r"[ \t]*(?:#{1,6}[ \t]*)?(?:\*\*|__|\*|_)?[ \t]*"
_THM_HEAD = re.compile(r"^" + _LABEL + r"(?:Théorème|Theoreme|Theorem|Énoncé|Enoncé|Statement|Proposition|Lemme|Lemma|"
                       r"Corollaire|Corollary)\b", re.I)
_PROOF_HEAD = re.compile(r"(?m)^" + _LABEL + r"(?:Démonstration|Demonstration|Preuve|Proof)\b[ \t]*"
                         r"(?:\([^)\n]*\))?[ \t]*[.:]?[ \t]*(?:\*\*|__|\*|_)?[ \t]*[.:]?[ \t]*")


def strip_restated_theorem(text: str) -> str:
    """The informal proof without the model's restatement of the theorem (« **Théorème.** … ») and without its own
    « Démonstration. » label: the document already prints the statement block and a « Démonstration » heading
    (2026-11-21: the PDF repeated the theorem right before the proof)."""
    t = (text or "").strip()
    if not t:
        return t
    m = _PROOF_HEAD.search(t)
    if m is None:
        return t
    before = t[:m.start()].strip()
    if not before or not _THM_HEAD.match(before):
        return t                          # no restated theorem before the label (or a label inside the text)
    rest = t[m.end():].strip()
    return rest or t


def proof_body(text: str) -> str:
    """The informal proof for a `proof` environment, which prints « Démonstration. » / « Proof. » and the end mark
    itself: no restated theorem, no leading proof label, no trailing □ (the article printed « Théorème. … »
    and « Démonstration. » twice inside its proofs)."""
    t = strip_restated_theorem(text)
    m = _PROOF_HEAD.match(t)
    if m and m.end() < len(t) and (t[m.start():m.end()].strip().endswith((".", ":", "*", "_")) or
                                   t[m.end():m.end() + 1] == "\n"):
        t = t[m.end():]
    return re.sub(r"\s*[□∎■]\s*$", "", t.strip()).strip()


_SEC_MD = re.compile(r"^\s{0,3}#{1,6}\s+(.*)$")
# « 1. **Énoncé du théorème :** » / « **Idée de la preuve** » alone on their line: a section title, not a list item
_SEC_BOLD = re.compile(r"^(?:\d+[.)]\s+)?(?:\*\*|__)([^*_`\n]{2,90}?)(?:\*\*|__)\s*[:.]?\s*$")
_SEC_NUM = re.compile(r"^\s*(?:\d+|[IVX]+)[.)]\s*")
_SEC_STATEMENT = re.compile(r"^(?:l['’]\s*)?(?:énoncé|enoncé|enonce|statement|théorème|theoreme|theorem|"
                            r"rappel de l['’]énoncé|the theorem|what the theorem says)\b", re.I)
_SEC_KNOWN = re.compile(r"^(?:l['’]\s*)?(?:idée|idee|idea|étapes?|etapes?|steps?|commentaires?|comments?|explication|"
                        r"explanation|déroulement|walkthrough)\b", re.I)


def _section_title(line: str) -> str | None:
    m = _SEC_MD.match(line) or _SEC_BOLD.match(line.rstrip())
    if m is None:
        return None
    title = re.sub(r"[*_]{2}", "", m.group(1)).strip()
    return _SEC_NUM.sub("", title).strip().rstrip(" :.").strip() or None


def document_explanation(text: str) -> str:
    """The AI explanation as printed in the document (PDF / HTML / Markdown, 2026-11-22): the document already prints
    the statement, so the model's section that restates it (« 1. Énoncé du théorème en langage mathématique courant »)
    is dropped, and the model's own section numbers (« 1. », « 2. », « 3. ») are removed from its titles so that only
    the list of steps is numbered — the annex used to read « 1. Énoncé… 2. Idée… 3. Étapes » then « 1. 2. 3. » again.
    Text without sections is returned unchanged."""
    lines = (text or "").strip().split("\n")
    # « 1. **intro x** » may be a step of the list: numbered bold lines are titles only when one of them reads like
    # the prompt's sections (statement / idea / steps)
    numbered = [t for ln in lines if re.match(r"\d+[.)]\s", ln) and (t := _section_title(ln))]
    numbered_ok = any(_SEC_STATEMENT.match(t) or _SEC_KNOWN.match(t) for t in numbered)
    sections: list[tuple[str | None, list[str]]] = [(None, [])]
    for ln in lines:
        title = _section_title(ln)
        if title is not None and re.match(r"\d", ln) and not numbered_ok:
            title = None
        if title is not None and not re.match(r"\s", ln):
            sections.append((title, []))
        else:
            sections[-1][1].append(ln)
    if len(sections) == 1:
        return (text or "").strip()               # no section titles: nothing to rework
    kept = [(t, body) for t, body in sections if t is None or not _SEC_STATEMENT.match(t)]
    if not any("".join(body).strip() for _t, body in kept):
        kept = sections                           # the statement was all there is: keep it
    out: list[str] = []
    for t, body in kept:
        if t is not None:
            out += ["", f"### {t}", ""]
        out += body
    res = re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()
    return res or (text or "").strip()


def collect(d: Dossier, lang: str = "fr", ws_info: dict | None = None, bib_keys: list[str] | None = None,
            bib_path: Path | None = None, bib_entries: list | None = None) -> Content:
    proved = d.proof_is_current
    stamp = None
    if proved:
        v = d.proofs[d.cur_proof]
        meta, ws = dict(v.meta or {}), dict(ws_info or {})
        checked = meta.get("checked") or v.t
        stamp = {"lean": meta.get("lean") or ws.get("lean") or "", "mathlib": meta.get("mathlib") or ws.get("mathlib") or "",
                 "workspace": meta.get("workspace") or ws.get("workspace") or d.workspace,
                 "date": _dt.datetime.fromtimestamp(float(checked)).date() if checked else None,
                 "axioms": meta.get("axioms"), "model": v.model, "strategy": meta.get("strategy", ""),
                 "seconds": meta.get("seconds")}
    has_statement_block = bool((d.understood_display or d.problem or d.understood or "").strip())
    informal = (strip_restated_theorem(d.informal_proof) if has_statement_block else d.informal_proof) if proved else ""
    return Content(
        title=d.title or "Sans titre", kind=d.kind or "theorem", theorem=d.theorem,
        nl_statement=(d.understood_display or d.problem or d.understood or "").strip(),
        lean_statement=d.statement, notes=d.notes,
        informal=informal or (document_explanation(d.explanation) if proved else ""),
        informal_is_explanation=proved and not informal and bool(d.explanation),
        proof=d.proof if proved else "", proved=proved, stamp=stamp,
        explanation=document_explanation(d.explanation) if (proved and informal) else "", date=_dt.date.today(), lang=lang if lang in T else "fr",
        bib_keys=list(bib_keys or []), bib_path=bib_path, bib=_bib_entries(bib_entries, bib_keys, bib_path),
        conditional="" if proved else conditional_note(d, lang))


def conditional_note(d: Dossier, lang: str = "fr") -> str:
    """S-AX (D56): a proof that Lean accepts only by admitting results (cited literature, attachments, admitted plan
    lemmas) is printed as such — never as a proof — with what it rests on."""
    cond = (d.extra or {}).get("conditional_proof")
    if not isinstance(cond, dict) or cond.get("verdict") != "proved_modulo":
        return ""
    if cond.get("source") == "literature":
        refs = ", ".join(f"{c.get('short', '')} — {c.get('title', '')}" for c in cond.get("cited") or [])
        return (f"Preuve conditionnelle, NON vérifiée : Lean l'accepte en admettant {refs} (résultat cité, non prouvé "
                "en Lean)." if lang == "fr" else
                f"Conditional proof, NOT verified: Lean accepts it when it assumes {refs} (cited result, not proved "
                "in Lean).")
    names = ", ".join(cond.get("admitted") or [])
    return (f"Preuve conditionnelle, NON vérifiée : repose sur des lemmes admis ({names})." if lang == "fr" else
            f"Conditional proof, NOT verified: rests on admitted lemmas ({names}).")


def _bib_entries(entries: list | None, keys: list[str] | None, path: Path | None) -> list:
    """[(key, CSL item)] from explicit entries, else from a .bib file filtered by `keys`."""
    if entries:
        return [(k, it) for k, it in entries]
    if path is None or not Path(path).is_file():
        return []
    from .research import biblio
    items, _err = biblio.bibtex_to_items(Path(path).read_text(encoding="utf-8", errors="replace"))
    pairs = [(it["_key"], it) for it in items]
    return [p for p in pairs if not keys or p[0] in keys]


# ---------------------------------------------------------------- bibliography (S-E)
def bib_backend() -> str:
    """biblatex + biber when both are installed, else bibtex + amsalpha, else a hand-formatted thebibliography."""
    if tectonic_cmd():
        return "bibtex"              # tectonic runs its built-in BibTeX itself (amsalpha.bst is in the pinned bundle)
    if deps.tool("biber") and texio.tex_font_file("biblatex.sty"):
        return "biblatex"
    if deps.tool("bibtex") and texio.tex_font_file("amsalpha.bst"):
        return "bibtex"
    return "manual"


def bib_file(c: Content) -> str:
    from .research import biblio
    return "".join(biblio.item_to_bibtex(it, k) + "\n" for k, it in c.bib)


def bib_preamble(c: Content) -> str:
    if c.bib and c.bib_backend == "biblatex":
        return r"\usepackage[backend=biber,style=alphabetic,maxbibnames=99,giveninits=true]{biblatex}" + "\n" + \
            r"\addbibresource{refs.bib}"
    return ""


def bib_section(c: Content, f: texio.Fonts, title: str) -> str:
    from .research import biblio
    if not c.bib:
        return ""
    if c.bib_backend == "biblatex":
        return r"\printbibliography[title={" + _esc(title, f) + "}]"
    if c.bib_backend == "bibtex":
        return r"\renewcommand{\refname}{" + _esc(title, f) + "}" + "\n" + r"\nocite{" + \
            ",".join(k for k, _ in c.bib) + "}" + "\n" + r"\bibliographystyle{amsalpha}" + "\n" + \
            r"\bibliography{refs}"
    labels = biblio.labels_for(c.bib)
    out = [r"\renewcommand{\refname}{" + _esc(title, f) + "}", r"\begin{thebibliography}{MMMM99}"]
    for k, it in c.bib:
        out.append(r"\bibitem[" + _esc(labels[k], f) + "]{" + biblio.safe_key(k) + "} " +
                   biblio.reference_latex(it, lambda s: _esc(s, f)))
    out.append(r"\end{thebibliography}")
    return "\n".join(out)


def cite_keys(c: Content) -> dict:
    return {k: True for k, _ in c.bib}


def cite_text(text: str, c: Content) -> str:
    """Markdown / HTML: `[@key, loc]` → `[Wil95, loc]` (unknown keys → `[?]`)."""
    if not c.bib or "@" not in (text or ""):
        return text
    from .research import biblio
    labels = biblio.labels_for(c.bib)
    return biblio.CITE_GROUP.sub(lambda m: biblio.cite_to_text(m.group(1), labels) or m.group(0), text)


def _fmt_date(day: _dt.date | None, lang: str) -> str:
    if day is None:
        return "—"
    return day.strftime("%d/%m/%Y") if lang == "fr" else day.isoformat()


def _stamp_rows(c: Content) -> list[tuple[str, str]]:
    t, s = T[c.lang], c.stamp or {}
    ax = s.get("axioms")
    rows = [(t["lean"], s.get("lean") or "—"), (t["mathlib"], s.get("mathlib") or "—"),
            (t["date"], _fmt_date(s.get("date"), c.lang)),
            (t["axioms"], (", ".join(ax) if ax else t["no_axioms"]) if ax is not None else "—")]
    if s.get("model"):
        rows.append((t["model"], s["model"] + (f" ({s['strategy']})" if s.get("strategy") else "")))
    if s.get("workspace"):
        rows.append((t["workspace"], s["workspace"]))
    return rows


# ---------------------------------------------------------------- LaTeX
def _esc(s: str, f: texio.Fonts, mono: bool = False) -> str:
    return texio.wrap_uncovered(texio.escape_plain(s), f.mono if mono else f.main, f)


def build_tex(c: Content, verbatim: bool = False, f: texio.Fonts | None = None) -> str:
    """Complete .tex source (XeLaTeX or LuaLaTeX). `verbatim`: model texts printed literally (safe mode)."""
    f = f or texio.fonts()
    t = T[c.lang]

    cites = cite_keys(c) if c.bib else None

    def model_text(text: str) -> str:
        if verbatim:
            return texio.verbatim_text(text, f)
        nl = text.strip()
        if nl and not texio.looks_like_latex(nl) and not re.search(r"[*`#|@]|^\s*\d+[.)]\s", nl, re.M):
            return _esc(nl, f)
        return texio.sanitize_markdown(nl, f, cites)

    status = (r"\textcolor{MLok}{\textbf{" + t["verified"] + "}}") if c.proved else \
        (r"\textcolor{MLwarn}{\textbf{" + t["not_proved"] + "}}")
    kind = t.get(c.kind, t["theorem"])
    parts = [_preamble(c, f), r"\begin{document}", "",
             r"\begin{center}",
             r"{\LARGE\bfseries " + _esc(c.title, f) + r"\par}\vspace{6pt}",
             r"{\small\ttfamily " + _esc(c.theorem, f, True) + r"}\quad\textbullet\quad{\small " + status + r"}\par",
             r"\end{center}", r"\vspace{4pt}"]
    if c.nl_statement:
        parts += [r"\section*{" + t["statement"] + "}",
                  r"\begin{MLstatement}{" + kind + "}", model_text(c.nl_statement), r"\end{MLstatement}"]
    parts += [r"\section*{" + t["lean_statement"] + "}"]
    parts.append(texio.lean_listing(c.lean_statement, f=f) if c.lean_statement.strip() else _esc(t["no_statement"], f))
    if c.notes.strip():
        parts += [r"\subsection*{" + t["gloss"] + "}", r"\MLainote{" + t["ai_gloss"] + "}", "", model_text(c.notes)]
    if not c.proved:
        parts += ["", r"\begin{MLwarnbox}", _esc(t["not_proved_text"], f), r"\end{MLwarnbox}"]
        if c.conditional:
            parts += ["", r"\begin{MLwarnbox}", _esc(c.conditional, f), r"\end{MLwarnbox}"]
    else:
        if c.informal.strip():
            parts += [r"\section*{" + t["informal"] + "}", r"\MLainote{" + t["ai_note"] + "}", "",
                      model_text(c.informal)]
        parts += [r"\section*{" + t["lean_proof"] + "}", texio.lean_listing(c.proof, f=f), "",
                  r"\begin{MLstamp}{" + t["stamp"] + r" \textemdash\ " + t["verified"] + " " +
                  texio.wrap_uncovered("✓", f.main, f) + "}",
                  r"\begin{tabular}{@{}l@{\hspace{1.2em}}l@{}}"]
        for k, v in _stamp_rows(c):
            parts.append(r"\textbf{" + _esc(k, f) + r"} & \texttt{" + _esc(v, f, True) + r"}\\")
        parts += [r"\end{tabular}", r"\par\smallskip{\footnotesize " + _esc(t["strict"], f) + "}", r"\end{MLstamp}"]
        if c.explanation.strip():
            parts += [r"\section*{" + t["appendix"] + "}", r"\MLainote{" + t["ai_note"] + "}", "",
                      model_text(c.explanation)]
    if c.bib:
        parts += ["", bib_section(c, f, t["references"])]
    parts += ["", r"\vfill\begin{center}\footnotesize\color{black!55} " +
              _esc(t["generated"].format(date=_fmt_date(c.date, c.lang)), f) + r"\end{center}", r"\end{document}", ""]
    return "\n".join(parts)


