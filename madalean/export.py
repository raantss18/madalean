        f.preamble(),
        r"\usepackage[" + t["babel"] + "]{babel}",
        bib_preamble(c),
        r"\usepackage[dvipsnames]{xcolor}",
        r"\usepackage{fvextra}",
        r"\usepackage[most]{tcolorbox}",
        r"\usepackage{enumitem}",
        r"\usepackage{titlesec}",
        r"\usepackage{parskip}",
        r"\usepackage[hidelinks,pdftitle={" + _esc(title, f) + r"},pdfcreator={Madalean}]{hyperref}",
        r"\definecolor{MLaccent}{HTML}{1F4E79}\definecolor{MLok}{HTML}{1B7F3B}\definecolor{MLwarn}{HTML}{B35C00}",
        r"\titleformat*{\section}{\large\bfseries\color{MLaccent}}",
