# ---------------------------------------------------------------- Markdown / Lean / HTML
def build_md(c: Content) -> str:
    t = T[c.lang]
    out = [f"# {c.title}", "", f"`{c.theorem}` — **{t['verified'] if c.proved else t['not_proved']}**", ""]
    if c.nl_statement:
        out += [f"## {t['statement']}", "", c.nl_statement, ""]
    out += [f"## {t['lean_statement']}", "", "```lean4", c.lean_statement.strip() or t["no_statement"], "```", ""]
    if c.notes.strip():
        out += [f"### {t['gloss']}", "", f"*{t['ai_gloss']}*", "", c.notes.strip(), ""]
    if not c.proved:
        out += [f"> {t['not_proved_text']}", ""]
        if c.conditional:
            out += [f"> **{c.conditional}**", ""]
    else:
        if c.informal.strip():
            out += [f"## {t['informal']}", "", f"*{t['ai_note']}*", "", c.informal.strip(), ""]
        out += [f"## {t['lean_proof']}", "", "```lean4", c.proof.strip(), "```", "", f"## {t['stamp']}", ""]
        out += [f"- **{k}** : {v}" if c.lang == "fr" else f"- **{k}**: {v}" for k, v in _stamp_rows(c)]
        out += ["", f"*{t['strict']}*", ""]
        if c.explanation.strip():
            out += [f"## {t['appendix']}", "", f"*{t['ai_note']}*", "", c.explanation.strip(), ""]
    if c.bib:
        from .research import biblio
        labels = biblio.labels_for(c.bib)
        out += [f"## {t['references']}", ""] + [f"- [{labels[k]}] {biblio.reference_text(it)}" for k, it in c.bib] + [""]
    out += ["---", t["generated"].format(date=_fmt_date(c.date, c.lang)), ""]
    return cite_text("\n".join(out), c)


def build_lean(c: Content) -> str:
    t = T[c.lang]
    head = [f"/-! {c.title}", f"   {c.theorem} — {t['verified'] if c.proved else t['not_proved']}"]
    if c.proved:
        head += [f"   {k}: {v}" for k, v in _stamp_rows(c)]
    else:
        head.append(f"   {t['not_proved_text']}")
    head.append("   " + t["generated"].format(date=_fmt_date(c.date, c.lang)))
    body = (c.proof if c.proved else c.lean_statement).strip()
    return "\n".join(h.replace("-/", "- /") for h in head) + "\n-/\n\n" + body + "\n"


