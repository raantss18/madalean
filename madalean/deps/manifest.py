"""Reading `manifest.toml` and the conda-lock files (no third-party module: tomllib + a tiny lock reader)."""
from __future__ import annotations

import hashlib
import re
import tomllib
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import unquote

from . import LOCKS, MANIFEST, PKG_DIR


def load(path: Path | None = None) -> dict:
    with open(path or MANIFEST, "rb") as f:
        return tomllib.load(f)


def components(path: Path | None = None) -> dict[str, dict]:
    return load(path).get("components", {})


def component(name: str, path: Path | None = None) -> dict:
    c = components(path).get(name)
    if c is None:
        raise KeyError(name)
    return c


def sha256_file(path: Path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            b = f.read(chunk)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def lock_path(c: dict) -> Path:
    return PKG_DIR / c["lock"]


@dataclass
class LockedPackage:
    name: str
    version: str
    url: str
    sha256: str
    md5: str

    @property
    def filename(self) -> str:
        return unquote(self.url.rsplit("/", 1)[-1])          # "cddlib-1%210.94n…" → "cddlib-1!0.94n…" (epochs)

    @property
    def dist(self) -> str:
        """`name-version-build` as in conda-meta/<dist>.json."""
        f = self.filename
        return f[:-6] if f.endswith(".conda") else f[:-8] if f.endswith(".tar.bz2") else f


def read_lock(path: Path, platform: str = "linux-64") -> list[LockedPackage]:
    """Packages of a conda-lock (unified v1 YAML) file for one platform. The file is generated by conda-lock in a
    fixed layout, so a line reader is enough (no PyYAML at run time)."""
    pkgs: list[LockedPackage] = []
    cur: dict = {}
    in_hash = False

    def flush():
        if cur.get("platform") == platform and cur.get("manager", "conda") == "conda" and cur.get("url"):
            pkgs.append(LockedPackage(cur.get("name", ""), str(cur.get("version", "")), cur["url"],
                                      cur.get("sha256", ""), cur.get("md5", "")))
    for raw in path.read_text(encoding="utf-8").splitlines():
        if raw.startswith("- name:"):
            flush()
            cur, in_hash = {"name": raw.split(":", 1)[1].strip()}, False
            continue
        if not cur:
            continue
        m = re.match(r"^  (\w+):\s*(.*)$", raw)
        if m:
            key, val = m.group(1), m.group(2).strip().strip("'\"")
            in_hash = key == "hash"
            if key in ("version", "manager", "platform", "url"):
                cur[key] = val
            continue
        m = re.match(r"^    (md5|sha256):\s*(\S+)", raw)
        if m and in_hash:
            cur[m.group(1)] = m.group(2)
    flush()
    return pkgs


def lock_hash(c: dict) -> str:
    return sha256_file(lock_path(c))


def lock_versions(c: dict) -> dict[str, str]:
    return {p.name: p.version for p in read_lock(lock_path(c))}


